#!/usr/bin/env python3
"""Build evals/RESULTS.md from the JSON files in evals/results/. Offline, no credentials."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIELDS = ["docType", "supplier", "order_ref", "status", "order_date", "currency", "items"]


def main():
    files = sorted(glob.glob(os.path.join(HERE, "results", "*.json")))
    lines = ["# Results", "", "Generated by `make_report.py` from `results/*.json`. Synthetic data only.", ""]
    if not files:
        lines.append("No runs recorded yet. Run `run_evals.py` for each prompt, then `make_report.py`.")
    else:
        header = "| Prompt | Model | Runs per case | Cases fully correct | Invalid JSON | " + " | ".join(FIELDS) + " |"
        lines += [header, "|" + "---|" * (5 + len(FIELDS))]
        for f in files:
            d = json.load(open(f, encoding="utf-8"))
            s, m = d["summary"], d["meta"]
            cells = []
            for field in FIELDS:
                v = s["fields"].get(field)
                cells.append("%d/%d" % (v["correct"], v["scored"]) if v else "-")
            lines.append("| %s | %s | %d | %d/%d | %d | %s |" % (
                os.path.basename(m["prompt"]), m["model"], m["repeat"], s["passed"], s["cases"], s["invalid_json"], " | ".join(cells)))
        lines += ["", "## Cases that failed", ""]
        for f in files:
            d = json.load(open(f, encoding="utf-8"))
            failed = sorted({c["id"] + " (" + c["tag"] + ")" for c in d["cases"] if not c["passed"]})
            lines.append("- **%s**: %s" % (os.path.basename(d["meta"]["prompt"]), ", ".join(failed) if failed else "none"))
    open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("Wrote evals/RESULTS.md")


if __name__ == "__main__":
    main()
